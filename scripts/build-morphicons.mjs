/** Build the browser-only icon driver from the user's local Morphicons 2.0.2 archive. */
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
const result = await build({
  entryPoints: ['third_party/morphicons-2.0.2/src/dom/index.ts'],
  bundle: true,
  format: 'iife',
  globalName: 'Morphicons',
  minify: true,
  platform: 'browser',
  target: 'es2022',
  write: false,
});
await writeFile(
  'packages/cli/src/services/morphiconsBundle.ts',
  `/**\n * Generated by scripts/build-morphicons.mjs.\n * Morphicons 2.0.2, MIT (c) Guillermo. See third_party/morphicons-2.0.2/LICENSE.\n */\nexport const morphiconsBundle = ${JSON.stringify(result.outputFiles[0].text)};\n`,
);
console.log(
  `Morphicons browser bundle: ${result.outputFiles[0].contents.length} bytes`,
);
